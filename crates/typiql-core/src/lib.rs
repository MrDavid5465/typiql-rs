pub use typiql_macros::{typiql_schema, typiql_type};

use serde::{Deserialize, Serialize};

/// Implement this trait (via `#[typiql_type]`) on any struct you want typiql to manage.
pub trait TypiQLType: for<'de> Deserialize<'de> + Serialize + Send + Sync + 'static {
    /// The InputObject type generated by `#[typiql_type]` for mutations.
    type Input: Serialize + for<'de> Deserialize<'de> + Default + Send + Sync;

    fn type_name() -> &'static str;
    fn key_field() -> &'static str;
    fn collection_name() -> &'static str;

    /// Which registered adapter (see `typiql_schema!`'s adapter map) stores
    /// this type. Defaults to `"default"` — the adapter most types use.
    /// Types declared `#[typiql_type(adapter = "duckdb")]` override this.
    fn adapter_name() -> &'static str {
        "default"
    }

    /// Column name/DuckDB-type pairs, derived at macro-expansion time from
    /// this type's own Rust field types. Only meaningful for types using the
    /// DuckDB adapter (`adapter_name() == "duckdb"`); empty for everything
    /// else. Lives on this trait (rather than only on the DuckDB adapter
    /// crate) so `DuckDbAdapter` can generically `CREATE TABLE IF NOT
    /// EXISTS` for any registered type without per-type hand-written DDL.
    fn duckdb_columns() -> &'static [(&'static str, &'static str)] {
        &[]
    }
}
